/**
 * Ширины размерных вариантов изображения (`streamer.API#78`, `АДП-Ф-23`).
 * Список фиксирован для всего приложения, а не хранится в БД на изображение
 * — вариант конкретного файла вычисляется по конвенции имени
 * (`image-variant.util.ts`), не читается из записи. Пересоздание при правке
 * этого списка — см. `regenerate-image-variants` (`npm run` скрипт).
 *
 * Числа взяты из реальных мест показа на эталонном экране (Full HD,
 * `CONTENT_MAX_WIDTH_PX = 1920` во фронтенде, `frontend/src/app/shared/utils/breakpoints.ts`)
 * вместе с их удвоенной (retina) версией — 1x и 2x одного и того же места
 * считаются двумя разными вариантами, не одним:
 *
 *  - 175  — превью строки ленты, 1x (АДП-Ф-23 называет это число явно)
 *  - 330  — мелкая ячейка витрины (1 колонка из 3), 1x: витрина при
 *           эталонной ширине содержимого 1030 (`NEWS_PAGE_GRID_REFERENCE_WIDTH_PX`,
 *           `news-layout.ts`), gap между колонками 20 → (1030 − 2×20) / 3 = 330
 *  - 350  — превью строки ленты, 2x
 *  - 480  — деталка на мобильном (`bp.small`), 1x: `news-detail-modal.scss`
 *           открывается нижней шторкой на всю ширину экрана, точного макета
 *           под мобильную версию нет — оценка под типичный узкий вьюпорт
 *  - 660  — мелкая ячейка витрины, 2x
 *  - 680  — средняя ячейка витрины (2 колонки из 3), 1x: 2×330 + 20 (gap)
 *  - 720  — деталка на десктопе, 1x: `.news-detail-modal__picture` — 60% от
 *           `width: min(1200px, 86vw)`, на широких экранах капается 1200px
 *  - 960  — деталка на мобильном, 2x
 *  - 1030 — крупная/полноширинная ячейка витрины (3 колонки из 3), 1x
 *  - 1360 — средняя ячейка витрины, 2x
 *  - 1440 — деталка на десктопе, 2x
 *  - 2060 — крупная ячейка витрины, 2x
 */
export const IMAGE_VARIANT_WIDTHS_PX: readonly number[] = [
  175, 330, 350, 480, 660, 680, 720, 960, 1030, 1360, 1440, 2060,
];
