const DATE_ONLY = /^\d{4}-\d{2}-\d{2}$/;

/**
 * Приводит границу периода публикации к моменту времени, который её самоё
 * ВКЛЮЧАЕТ (ФИЛ-О-02).
 *
 * Дата без времени (`2026-08-27`) называет день целиком, а не его полночь:
 * нижняя граница разворачивается в начало этого дня, верхняя — в конец.
 * Иначе `publishedTo=2026-08-27` молча отрезал бы весь день. Полный
 * ISO-datetime уже называет момент и берётся как есть — вместе со смещением,
 * если оно указано.
 */
export function toInclusiveBoundary(
  value: string,
  edge: 'start' | 'end',
): Date {
  if (DATE_ONLY.test(value)) {
    const time = edge === 'start' ? '00:00:00.000' : '23:59:59.999';
    return new Date(`${value}T${time}Z`);
  }

  return new Date(value);
}
